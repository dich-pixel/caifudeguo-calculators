// Derives src/generated/av-depot-exposed.ts for the early-withdrawal layer (src/early-exit.ts, PLAN_stage5.md C.1).
// It is exactly the precise copy (scripts/precise-core.mjs: imports re-pointed, depotPair returns raw numbers)
// plus ONE export line, so the layer can call the core's own internal functions instead of re-writing them.
// No formula, constant or schema changes. test/exposed-core.test.mjs and caifudeguo/check-core.mjs check it is
// up to date. Regenerate: node caifudeguo/av-ui/scripts/exposed-core.mjs
import { writeFileSync } from 'node:fs'
import process from 'node:process'
import { generate as generatePrecise } from './precise-core.mjs'

const outUrl = new URL('../src/generated/av-depot-exposed.ts', import.meta.url)

export const EXPORT_LINE = 'export { calculateAvDepotSavings, calculateDepotSavings, calculateZulagen, germanIncomeTax, grenzsteuer, günstigerprüfung }\n'

export function generate() {
  const precise = generatePrecise().split('\n')
  // replace the two header comment lines of the precise copy
  const body = precise.slice(2).join('\n')
  return `// GENERATED by caifudeguo/av-ui/scripts/exposed-core.mjs from src/calculators/av-depot.ts (finanzfluss/calculators dcc29a6, AGPL-3.0).\n// Do not edit. Same as av-depot-precise.ts (amounts as numbers) plus the export line at the end; no formula changes.\n${body}${EXPORT_LINE}`
}

if (process.argv[1] && import.meta.url.endsWith(process.argv[1].split('/').pop())) {
  writeFileSync(outUrl, generate())
  console.warn('written', outUrl.pathname)
}
