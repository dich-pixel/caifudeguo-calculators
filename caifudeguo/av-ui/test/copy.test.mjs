// Generates caifudeguo/av-ui/COPY.md from the same string constants the UI renders (src/strings.ts).
// Check: `pnpm vitest run caifudeguo` (fails when COPY.md is stale). Regenerate: `UPDATE_COPY=1 pnpm vitest run caifudeguo`.
import { readFileSync, writeFileSync } from 'node:fs'
import process from 'node:process'
import { expect, it } from 'vitest'
import { formatNumberDe } from '../src/format.ts'
import { errorDomTestIds, QUICK_AMOUNTS } from '../src/model.ts'
import { detailsToggleTestId, documentTitle, h1Text, NOTICE_DETAIL_KEYS, PAYOUT_GROUPS, STR, termsOf, YEARLY_COL_KEYS, yearlyHeadTestId, yearlyHeadText } from '../src/strings.ts'

const root = new URL('..', import.meta.url)
const stringsSrc = readFileSync(new URL('src/strings.ts', root), 'utf8').split('\n')
const mainSrc = readFileSync(new URL('src/main.ts', root), 'utf8').split('\n')
const modelSrc = readFileSync(new URL('src/model.ts', root), 'utf8').split('\n')
const indexHtml = readFileSync(new URL('index.html', root), 'utf8')

function lineOf(lines, re) {
  const i = lines.findIndex(l => re.test(l))
  return i === -1 ? '–' : String(i + 1)
}

const esc = s => String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ')

function testIds(key) {
  const fromError = errorDomTestIds(key)
  if (fromError)
    return fromError
  if (key === 'gross' || key === 'tax' || key === 'net')
    return PAYOUT_GROUPS.map(group => `${STR[key].id}-${group}`)
  if (key === 'noticeDetailsSummary')
    return NOTICE_DETAIL_KEYS.map(detailsToggleTestId)
  return [STR[key].id]
}

function visibleText(key) {
  return key === 'title' ? h1Text() : STR[key].zh
}

function fileCell(defLine, useLine, extra = []) {
  const parts = [`caifudeguo/av-ui/src/strings.ts:${defLine}`]
  if (useLine !== '–')
    parts.push(`caifudeguo/av-ui/src/main.ts:${useLine}`)
  parts.push(...extra)
  return parts.join('；')
}

function row(testids, zh, terms, file) {
  const de = terms.map(item => item.term).join('；')
  const source = terms.map(item => item.source || '—').join('；')
  const id = testids.map(item => `\`${item}\``).join('、')
  return `| ${id} | ${esc(zh)} | ${esc(de)} | ${esc(source)} | ${esc(file)} |`
}

function generate() {
  const out = [
    '# AV-Depot 界面文案',
    '',
    '<!-- Generated by caifudeguo/av-ui/test/copy.test.mjs from src/strings.ts. Do not edit by hand. -->',
    '',
    '每一行是一条用户能看到的文案。`data-testid` 是显示它的元素；带 `{n}`、`{field}` 的是重复控件（第 n 个孩子、某个输入项）。',
    '德语术语一列：文案里写出来的德语，以及这个控件对应的官方德语名（普通标签只显示中文；标题和逐年表会把德语加在括号里）。有法条的写明出处；没有法条的写 `kein Normzitat` 或 `—`。',
    '`{x}` 金额，`{min}` / `{max}` 边界，`{year}` 年份，`{date}` 参数核对日期，`{sha}` 短 commit，`{a}` / `{b}` 两边的每月到手。',
    '定义在 `caifudeguo/av-ui/src/strings.ts`，页面在 `caifudeguo/av-ui/src/main.ts` 用同一常量渲染。',
    '',
    '| data-testid | 用户可见文案 | 德语术语 | 法律或官方出处 | 文件 |',
    '| --- | --- | --- | --- | --- |',
  ]
  for (const [key] of Object.entries(STR)) {
    const defLine = lineOf(stringsSrc, new RegExp(`^\\s*${key}: s\\(`))
    const useRe = key === 'title'
      ? /h1Text\(/
      : new RegExp(`'${key}'|STR\\.${key}\\b`)
    const useLine = lineOf(mainSrc, useRe)
    const extra = []
    // Only error strings are chosen in model.ts. Field names such as 'age' are not this copy.
    if (errorDomTestIds(key)) {
      const modelLine = lineOf(modelSrc, new RegExp(`'${key}'`))
      if (modelLine !== '–')
        extra.push(`caifudeguo/av-ui/src/model.ts:${modelLine}`)
      if (useLine === '–')
        extra.push(`caifudeguo/av-ui/src/main.ts:${lineOf(mainSrc, /t\(e\.key/)}`)
    }
    out.push(row(testIds(key), visibleText(key), termsOf(key), fileCell(defLine, useLine, extra)))
  }

  const titleLine = lineOf(stringsSrc, /export function documentTitle/)
  const titleUse = lineOf(mainSrc, /documentTitle\(/)
  out.push(row(
    ['document-title'],
    documentTitle(),
    termsOf('title'),
    fileCell(titleLine, titleUse, ['caifudeguo/av-ui/index.html']),
  ))

  const quickLine = lineOf(mainSrc, /`quick-\$\{amount\}`/)
  for (const amount of QUICK_AMOUNTS) {
    out.push(row(
      [`quick-${amount}`],
      formatNumberDe(amount),
      [],
      `caifudeguo/av-ui/src/main.ts:${quickLine}`,
    ))
  }

  const headLine = lineOf(mainSrc, /yearlyHeadText\(/)
  for (const side of ['av', 'normal']) {
    for (const key of YEARLY_COL_KEYS) {
      out.push(row(
        [yearlyHeadTestId(side, key)],
        yearlyHeadText(side, key),
        termsOf(key),
        `caifudeguo/av-ui/src/strings.ts:${lineOf(stringsSrc, /export function yearlyHeadText/)}；caifudeguo/av-ui/src/main.ts:${headLine}`,
      ))
    }
  }

  out.push(
    '',
    '## 说明',
    '',
    '- 页面 `<title>` 与 `documentTitle()` 相同，并标 `data-testid="document-title"`。',
    '- `<h1 data-testid="title">` 的可见文字是 `h1Text()`（中文标题 + 德语产品名）。',
    '- 快捷按钮的文字是德式整数金额，没有另外的中文句子。',
    '- 逐年表表头由列文案加上「AV ·」或「普通 ETF 账户 ·」组成，括号里的德语来自同一条常量。',
    '- 结果金额（`result-monthly-av`、`result-monthly-normal`、`cell-*`）是计算出来的德式金额，不是固定句子。',
    '',
    '## Werbung/Anzeige（§5a Abs. 4 UWG）',
    '',
    '本页目前没有联盟、推荐或广告链接，所以不显示「Werbung」或「Anzeige」。',
    '以后如果在页面上或 iframe 旁边放券商返佣链接，必须同时显示「Werbung」或「Anzeige」，并在 `src/strings.ts` 里给它单独的 data-testid。插件说明见 `caifudeguo/wp-plugin/caifudeguo-av-depot/readme.txt`。',
    '',
    '出处：BGBl. 2026 I Nr. 156（Altersvorsorgereformgesetz）。「n.F.」指 2027 年起生效的文本。',
    '',
  )
  return out.join('\n')
}

it('cOPY.md is generated from src/strings.ts and the page uses those strings', () => {
  expect(indexHtml).toContain(`<title>${documentTitle()}</title>`)
  expect(h1Text()).toBe('养老投资账户计算器（Altersvorsorgedepot）')
  const path = new URL('COPY.md', root)
  const content = generate()
  if (process.env.UPDATE_COPY)
    writeFileSync(path, content)
  expect(readFileSync(path, 'utf8')).toBe(content)
})
