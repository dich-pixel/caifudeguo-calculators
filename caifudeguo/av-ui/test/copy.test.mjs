// Generates caifudeguo/av-ui/COPY.md from the same string constants the UI renders (src/strings.ts).
// Check: `pnpm vitest run caifudeguo` (fails when COPY.md is stale). Regenerate: `UPDATE_COPY=1 pnpm vitest run caifudeguo`.
import { readFileSync, writeFileSync } from 'node:fs'
import process from 'node:process'
import { expect, it } from 'vitest'
import { STR } from '../src/strings.ts'

const root = new URL('..', import.meta.url)
const stringsSrc = readFileSync(new URL('src/strings.ts', root), 'utf8').split('\n')
const mainSrc = readFileSync(new URL('src/main.ts', root), 'utf8').split('\n')

function lineOf(lines, re) {
  const i = lines.findIndex(l => re.test(l))
  return i === -1 ? '–' : String(i + 1)
}

const esc = s => String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ')

function generate() {
  const out = [
    '# AV-Depot UI — copy deck / 文案清单',
    '',
    '<!-- Generated by caifudeguo/av-ui/test/copy.test.mjs from src/strings.ts. Do not edit by hand. -->',
    '',
    'Every user-visible string of the page, with the `data-testid` of the element that shows it.',
    '“strings.ts” = line of the definition in `caifudeguo/av-ui/src/strings.ts`; “main.ts” = first line in',
    '`caifudeguo/av-ui/src/main.ts` that renders it. Placeholders: `{x}` amount, `{min}`/`{max}` bound,',
    '`{year}` year, `{date}` = `PARAMS_CHECK_DATE` in `src/params.ts`, `{sha}` short commit.',
    'German terms: the term shown in brackets and its legal/official source. Sources marked',
    '“kein eigener Gesetzesbegriff” are calculator wording, not statutory terms.',
    '',
    '| data-testid | key | 中文 | German term | source | strings.ts | main.ts |',
    '| --- | --- | --- | --- | --- | --- | --- |',
  ]
  for (const [key, v] of Object.entries(STR)) {
    const defLine = lineOf(stringsSrc, new RegExp(`^\\s*${key}: s\\(`))
    const useLine = lineOf(mainSrc, new RegExp(`'${key}'|STR\\.${key}\\b`))
    out.push(`| \`${v.id}\` | ${key} | ${esc(v.zh)} | ${esc(v.de)} | ${esc(v.source)} | ${defLine} | ${useLine} |`)
  }
  out.push(
    '',
    '## Werbung/Anzeige (§5a Abs. 4 UWG)',
    '',
    'The page currently contains no affiliate, referral or promotional links, so no „Werbung/Anzeige“ label is shown.',
    'Any future affiliate/referral link (on the page or next to the iframe) must be accompanied by a visible',
    '„Werbung“ or „Anzeige“ label (add it to src/strings.ts with its own data-testid). See also wp-plugin readme.txt.',
    '',
    'Sources: BGBl. 2026 I Nr. 156 (Altersvorsorgereformgesetz); „n.F.“ = version in force from 2027.',
    '',
    '## Composite strings built in main.ts',
    '',
    '- Page `<title>` (`index.html`): `title` + `（Altersvorsorgedepot）· caifudeguo.de`.',
    '- `<h1 data-testid="title">`: `title` + `（` + German term + `）`.',
    '- Yearly table column labels: `AV · ` / `普通 ETF 账户 · ` + column string + `（German term）` when the column has one.',
    '- Quick buttons `quick-120`, `quick-1800`, `quick-13680`: German-formatted amounts 120 / 1.800 / 13.680.',
    '- Result values (`result-monthly-av`, `result-monthly-normal`, `cell-*`): German-formatted euro amounts from the core.',
    '',
  )
  return out.join('\n')
}

it('cOPY.md is generated from src/strings.ts', () => {
  const path = new URL('COPY.md', root)
  const content = generate()
  if (process.env.UPDATE_COPY)
    writeFileSync(path, content)
  expect(readFileSync(path, 'utf8')).toBe(content)
})
